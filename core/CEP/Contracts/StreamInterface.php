declare(strict_types=1);

namespace NetFusion\Core\CEP\Contracts;

use NetFusion\Core\CEP\Stream\KeyedStream;

interface StreamInterface
{
    /**
     * Get stream name / identifier.
     */
    public function getName(): string;

    /**
     * Filter stream events with a predicate closure/callback.
     */
    public function filter(callable $predicate): self;

    /**
     * Transform each stream event.
     */
    public function map(callable $mapper): self;

    /**
     * Flat-map each stream event into 0 or more events.
     */
    public function flatMap(callable $flatMapper): self;

    /**
     * Partition stream by a key selector closure or property name.
     */
    public function keyBy(string|callable $keySelector): StreamInterface|KeyedStream;

    /**
     * Attach a sink connector to receive stream outputs.
     */
    public function sink(SinkInterface|callable $sink): self;

    /**
     * Process an incoming event through this stream pipeline.
     *
     * @return array<mixed> Outputs generated by downstream operators
     */
    public function emit(EventInterface $event): array;
}
